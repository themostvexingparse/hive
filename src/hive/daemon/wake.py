NOTES_MARKER_CHARS = 200
NOTES_SHOWN_CHARS = 2000


def notes_marker(notes: str) -> str:
    """What a session remembers of a task's notes: their last characters. Notes are only ever
    appended to (and trimmed at the front past 20,000 characters), so the notes added since
    are whatever follows this text."""
    return notes[-NOTES_MARKER_CHARS:]


def new_notes(notes: str, marker) -> str | None:
    """Notes added since the session saw `marker`; None if that can't be told (old format,
    or the marker is gone), in which case the caller resends the notes rather than risk
    leaving something out."""
    if not isinstance(marker, str):
        return None
    if not marker:
        return notes
    pos = notes.find(marker)  # the first match errs towards repeating notes, never dropping
    return None if pos < 0 else notes[pos + len(marker):]


def _notes_tail(notes: str) -> str:
    """The newest notes, saying so when older ones are left out."""
    notes = notes.strip()
    if len(notes) <= NOTES_SHOWN_CHARS:
        return notes
    return "(earlier notes cut; task_get has them all) …" + notes[-NOTES_SHOWN_CHARS:]


def build_prompt(slot: str, me: dict, fleet: dict, triggers: list[dict], messages: list[dict],
                 tasks: list[dict], first_in_session: bool, project_prompt: str = "",
                 seen: dict[int, str] | None = None, handoff: str = "") -> str:
    """`project_prompt`: the project's role files (.hive/prompts/roles/), added once per
    session next to the role prompt. `seen`: tasks this session was already shown, mapped to
    the notes it saw (notes_marker); only what's new about them is sent again. `handoff`: what
    a fresh session needs to pick up work begun in an earlier one."""
    seen = seen or {}
    roles = ", ".join(me.get("roles", []))
    parts = [f"[HIVE WAKE] You are agent `{slot}` (roles: {roles}). Fleet state: "
             f"{fleet.get('state')}. Time: {time.strftime('%Y-%m-%d %H:%M:%S')}. "
             "Use the hive-worker skill."]
    if first_in_session and me.get("role_prompt"):
        parts.append(me["role_prompt"])
    if first_in_session and project_prompt:
        parts.append(project_prompt)
    if "orchestrator" in me.get("roles", []):
        parts.append(orchestrator_guidance(fleet))
    if triggers:
        parts.append("Why you were woken:\n" + "\n".join(f"- {t['summary']}" for t in triggers))
    if tasks:
        lines = []
        for t in tasks:
            lines.append(f"- Task #{t['id']} [{t['state']}] ({t['kind']}): {t['title']}")
            notes = t.get("notes") or ""
            if t["id"] in seen:  # this session has the spec already: only new notes
                new = new_notes(notes, seen[t["id"]])
                if new is None:
                    extra = "\n  Notes (latest): " + _notes_tail(notes).replace("\n", "\n  ")
                else:
                    new = new.strip()
                    extra = ("\n  New notes: " + _notes_tail(new).replace("\n", "\n  ")
                             if new else "")
                lines.append("  (Spec as before in this session.)" + extra)
                continue
            if t.get("spec"):
                lines.append("  Spec: " + t["spec"].strip().replace("\n", "\n  ")[:4000])
            if t.get("path_hints"):
                lines.append(f"  Path hints: {', '.join(t['path_hints'])}")
            if notes:
                lines.append("  Notes: " + _notes_tail(notes).replace("\n", "\n  "))
        parts.append("Your tasks:\n" + "\n".join(lines))
    if handoff:
        parts.append(handoff)
    if messages:
        parts.append("New messages:\n" + "\n".join(fmt_message(m) for m in messages))
    if first_in_session:
        parts.append(GUIDE)
    return "\n\n".join(parts)


def orchestrator_guidance(fleet: dict) -> str:
    """Short state-specific reminder; the full procedure lives in the hive-orchestrator skill."""
    state = fleet.get("state")
    if state in ("setup", "paused"):
        return {"setup": "The fleet is in SETUP: no goal yet. Don't plan or explore; wait "
                         "with await_events until the user starts the fleet.",
                "paused": "The fleet is PAUSED by the user; only communicate, and wait with "
                          "await_events until it resumes."}[state]
    return {
        "planning": f"The fleet is PLANNING. Goal: {fleet.get('goal') or '(see #user)'}. Create "
                    "draft tasks, then decision_request(kind='start_approval').",
        "awaiting_approval": "The plan awaits the user's approval; do not start work.",
        "frozen": "The fleet is FROZEN awaiting a user decision; only communicate.",
        "running": "Monitor, assign, unblock; raise decision_request(kind='stuck') if needed.",
    }.get(state, "") + " Keep state.md current; status_publish when the user should know."


def digest(fleet: dict, triggers: list[dict], messages: list[dict]) -> str:
    """Text returned by await_events / injected by hooks into the interactive orchestrator."""
    parts = [f"Fleet state: {fleet.get('state')} · {time.strftime('%H:%M:%S')}"]
    hint = orchestrator_guidance(fleet)
    if hint.strip():
        parts.append(hint.strip())
    if triggers:
        parts.append("Events:\n" + "\n".join(f"- {t['summary']}" for t in triggers))
    if messages:
        parts.append("Messages:\n" + "\n".join(fmt_message(m) for m in messages))
    return "\n\n".join(parts)


# ---------------------------------------------------------------------- per-session bundles

def bundle_dir(slot: Slot, vendor: str | None = None) -> Path:
    return Path(slot.worktree) / ".hive" / "agent" / (vendor or slot.vendor)


def slot_env(slot: Slot, local_url: str, secret: str) -> dict:
    env = dict(os.environ)
    # HIVE_HOME pins Hive's own folder for the hooks and MCP server, which an agy slot would
    # otherwise look for in its private home.
    env.update(HIVE_SLOT=slot.name, HIVE_DAEMON_URL=local_url, HIVE_LOCAL_SECRET=secret,
               HIVE_HOME=str(hive_home()), MCP_TOOL_TIMEOUT=str(MCP_TIMEOUT_MS))
    if slot.config_dir:
        if slot.vendor == "claude":
            env["CLAUDE_CONFIG_DIR"] = slot.config_dir
        elif slot.vendor == "codex":
            env["CODEX_HOME"] = slot.config_dir
        elif slot.vendor == "agy":
            env.update(agy_home_env(slot.config_dir))
        else:
            env["GEMINI_CLI_HOME"] = slot.config_dir
    return env


def agy_home_env(home: str) -> dict:
    """agy keeps its settings, plugins and conversations in ~/.gemini and has no setting to
    move them, so the slot's folder becomes its home directory. Commands the agent runs see
    that home too; git keeps the user's identity through GIT_CONFIG_GLOBAL. (The account
    login is in the OS keyring, shared by every agy on the machine.)"""
    env = {"USERPROFILE": home, "HOME": home}
    gitconfig = Path.home() / ".gitconfig"
    if "GIT_CONFIG_GLOBAL" not in os.environ and gitconfig.exists():
        env["GIT_CONFIG_GLOBAL"] = str(gitconfig)
    return env


def prepare_vendor(slot: Slot, env: dict, role_class: str = "worker") -> str | None:
    """Attach Hive to the slot's private CLI home before a launch, where the CLI needs it.
    Returns an error description if that failed, else None."""
    if slot.vendor == "gemini":
        return ensure_gemini_extension(slot, env)
    if slot.vendor == "codex":
        return ensure_codex_home(slot, role_class)
    if slot.vendor == "agy":
        return ensure_agy_home(slot, role_class)
    return None


def ensure_gemini_extension(slot: Slot, env: dict) -> str | None:
    """Link the repo's Hive extension into this slot's private Gemini home (never ~/.gemini).
    Returns an error description if linking failed, else None."""
    if slot.vendor != "gemini" or not slot.config_dir:
        return None
    marker = Path(slot.config_dir) / ".gemini" / "extensions" / "hive"
    if marker.exists():
        return None
    if not bundle_dir(slot).exists():
        return (f"Gemini extension missing at {bundle_dir(slot)}: run `hive init` in the "
                "repository and commit it")
    exe = shutil.which("gemini") or "gemini"
    try:
        p = subprocess.run([exe, "extensions", "link", str(bundle_dir(slot)), "--consent"],
                           env=env, capture_output=True, text=True, cwd=slot.worktree,
                           timeout=120)
    except (OSError, subprocess.TimeoutExpired) as e:
        return f"could not run `gemini extensions link`: {e}"
    if p.returncode != 0 or not marker.exists():
        return ("`gemini extensions link` failed: "
                + ((p.stderr or p.stdout or "").strip()[-500:] or f"exit {p.returncode}"))
    return None


def vendor_bundle(slot: Slot) -> dict[str, str]:
    """The repo's bundle for the slot's CLI as {path relative to .hive/agent/<vendor>/: text}.
    A repository initialised by an older Hive may have none yet; it is then generated in
    memory."""
    src = bundle_dir(slot)
    if src.exists():
        return {p.relative_to(src).as_posix(): p.read_text("utf-8")
                for p in src.rglob("*") if p.is_file()}
    from ..init import bundle_files, bundle_hive_cmd
    root = Path(slot.worktree)
    prefix = f"{slot.vendor}/"
    return {rel[len(prefix):]: text
            for rel, text in bundle_files(root, bundle_hive_cmd(root) or "hive").items()
            if rel.startswith(prefix)}


def ensure_codex_home(slot: Slot, role_class: str = "worker") -> str | None:
    """Copy the Hive profile, the role's execpolicy rules and the Hive skills into the slot's
    private CODEX_HOME (never ~/.codex). Refreshed on every launch, so `hive init` changes
    reach the next session. Returns an error description if that failed, else None."""
    if slot.vendor != "codex":
        return None
    if not slot.config_dir:
        return ("this Codex slot has no private config folder; re-run `hive join` so Hive "
                "can attach its tools without touching ~/.codex")
    try:
        files = vendor_bundle(slot)
    except Exception as e:  # e.g. a bad .hive/prompts/ file while generating
        return f"could not build Hive's Codex profile: {e}"
    profile = f"{CODEX_PROFILE}.config.toml"
    if profile not in files:
        return (f"Codex profile missing at {bundle_dir(slot) / profile}: run `hive init` in "
                "the repository and commit it")
    home = Path(slot.config_dir)
    wanted = {profile: files[profile]}
    if f"rules/{role_class}.rules" in files:
        wanted["rules/hive.rules"] = files[f"rules/{role_class}.rules"]
    wanted.update({rel: text for rel, text in files.items() if rel.startswith("skills/")})
    try:
        for rel, text in wanted.items():
            path = home / rel
            if not path.exists() or path.read_text("utf-8") != text:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, "utf-8")
    except OSError as e:
        return f"could not write Hive's Codex files into {home}: {e}"
    return None


def ensure_agy_home(slot: Slot, role_class: str = "worker") -> str | None:
    """Copy the Hive plugin into the slot's private agy home (never ~/.gemini) and enable it;
    set the role's permission rules and trust the worktree in the home's settings.json, so
    no trust prompt comes up. Refreshed on every launch, so `hive init` changes reach the next
    session. Returns an error description if that failed, else None."""
    if slot.vendor != "agy":
        return None
    if not slot.config_dir:
        return ("this agy slot has no private home folder; re-run `hive join` so Hive can "
                "attach its tools without touching ~/.gemini")
    try:
        files = vendor_bundle(slot)
    except Exception as e:  # e.g. a bad .hive/prompts/ file while generating
        return f"could not build Hive's agy plugin: {e}"
    if "plugin.json" not in files:
        return (f"agy plugin missing at {bundle_dir(slot)}: run `hive init` in the repository "
                "and commit it")
    gemini = Path(slot.config_dir) / ".gemini"
    plugin = gemini / "config" / "plugins" / AGY_PLUGIN
    worktree = os.path.normpath(os.path.abspath(slot.worktree))

    def settings(d: dict) -> None:
        perms = json.loads(files.get(f"settings/{role_class}.json", "{}")).get("permissions")
        if perms is not None:
            d["permissions"] = perms
        trusted = d.setdefault("trustedWorkspaces", [])
        if worktree not in trusted:
            trusted.append(worktree)

    try:
        for rel, text in files.items():
            if rel.startswith("settings/"):
                continue
            path = plugin / rel
            if not path.exists() or path.read_text("utf-8") != text:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, "utf-8")
        _update_json(gemini / "config" / "config.json", lambda d: d.setdefault(
            "plugins", {}).setdefault(AGY_PLUGIN, {}).update(enabled=True))
        _update_json(gemini / "antigravity-cli" / "settings.json", settings)
    except (OSError, ValueError, AttributeError) as e:
        return f"could not write Hive's agy files into {slot.config_dir}: {e}"
    return None


def _update_json(path: Path, change: Callable[[dict], None]) -> None:
    """Apply `change` to a JSON settings file, keeping everything else in it; written only if
    something changed. agy also accepts files with a byte order mark."""
    old = json.loads(path.read_text("utf-8-sig")) if path.exists() else {}
    if not isinstance(old, dict):
        raise ValueError(f"{path} does not hold a JSON object")
    new = json.loads(json.dumps(old))
    change(new)
    if new != old or not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(new, indent=2) + "\n", "utf-8")


_UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
# Codex's own log lines on stderr: `2026-10-20T08:32:33.63Z ERROR codex_core::…: error=…`.
_CODEX_LOG = re.compile(r"^\d{4}-\d\d-\d\dT[\d:.]+Z\s+(?:ERROR|WARN)\s+codex\S*:\s+"
                        r"(?:error=)?(.*?)\s*$")


def codex_latest_session(config_dir: str, since: float) -> str | None:
    """Id of the newest Codex session written in this CODEX_HOME since `since`. Codex picks
    its own ids, so an interactive session's id is only known afterwards; its transcript is
    sessions/YYYY/MM/DD/rollout-<time>-<id>.jsonl."""
    best: tuple[float, Path] | None = None
    for p in (Path(config_dir) / "sessions").rglob("rollout-*.jsonl"):
        try:
            mtime = p.stat().st_mtime
        except OSError:
            continue
        if mtime >= since - 1 and (best is None or mtime > best[0]):
            best = (mtime, p)
    m = _UUID.search(best[1].stem) if best else None
    return m.group(0) if m else None


def agy_latest_session(home: str, since: float) -> str | None:
    """Id of the newest agy conversation saved in this home since `since`; agy keeps each in
    .gemini/antigravity-cli/conversations/<id>.db."""
    best: tuple[float, str] | None = None
    for p in (Path(home) / ".gemini" / "antigravity-cli" / "conversations").glob("*.db"):
        try:
            mtime = p.stat().st_mtime
        except OSError:
            continue
        if mtime >= since - 1 and _UUID.match(p.stem) and (best is None or mtime > best[0]):
            best = (mtime, p.stem)
    return best[1] if best else None


def latest_session(slot: Slot, since: float) -> str | None:
    """The session an interactive CLI that picks its own ids (SELF_ID_VENDORS) used."""
    if not slot.config_dir:
        return None
    if slot.vendor == "codex":
        return codex_latest_session(slot.config_dir, since)
    if slot.vendor == "agy":
        return agy_latest_session(slot.config_dir, since)
    return None


def session_flags(vendor: str, session_id: str, resume: bool) -> list[str]:
    return ["--resume" if resume else "--session-id", session_id]


def model_flags(slot: Slot) -> list[str]:
    if not slot.model:
        return []
    return ["--model" if slot.vendor in ("claude", "agy") else "-m", slot.model]


def agy_message(prompt: str) -> str:
    """A prompt as agy's stream-json input: one `user` message per line."""
    return json.dumps({"event": "user", "message": {"content": prompt}}) + "\n"


def codex_mode_flags(mode: str, headless: bool) -> list[str]:
    """Sandbox (and for headless turns, approval) settings for a Codex launch. `-c` keys work
    both before `exec resume` and on the interactive CLI."""
    if mode == "yolo":
        return ["--dangerously-bypass-approvals-and-sandbox"]
    flags = ["-c", f'sandbox_mode="{mode}"'] if mode else []
    if headless:  # nobody can answer: failures go straight back to the model
        flags += ["-c", 'approval_policy="never"']
    return flags


def claude_settings_arg(slot: Slot, role_class: str) -> str:
    """The session's permission file from `hive init`; inline MCP-only rules for old bundles."""
    path = bundle_dir(slot, "claude") / "settings" / f"{role_class}.json"
    return str(path) if path.exists() else CLAUDE_SESSION_SETTINGS


def gemini_policy_args(slot: Slot, role_class: str) -> list[str]:
    path = bundle_dir(slot, "gemini") / "policies" / f"{role_class}.toml"
    return ["--policy", str(path)] if path.exists() else []


def build_command(slot: Slot, session_id: str, resume: bool,
                  role_class: str = "worker") -> list[str]:
    """Headless worker command; prompt goes on stdin (agy: as stream-json, see agy_message);
    output is stream-json."""
    mode = slot.permission_mode or DEFAULT_PERMISSION.get(slot.vendor, "")
    if slot.command:
        return [a.replace("{session}", session_id).replace("{mode}", mode)
                .replace("{session_flag}", "--resume" if resume else "--session-id")
                .replace("{bundle}", str(bundle_dir(slot)))
                for a in slot.command]
    if slot.vendor == "codex":
        # Codex chooses session ids itself: a new session's id arrives in `thread.started`.
        cmd = ["codex", "exec", "--json", *CODEX_SESSION_FLAGS,
               *codex_mode_flags(mode, headless=True), *model_flags(slot)]
        return cmd + (["resume", session_id, "-"] if resume else ["-"])
    if slot.vendor == "agy":
        # agy too chooses session ids itself: a new one's id arrives in `init`. It reads the
        # prompt from stdin only in stream-json form, and exits once stdin is closed.
        cmd = ["agy", "--input-format", "stream-json", "--output-format", "stream-json",
               *(["--mode", mode] if mode else []), *model_flags(slot)]
        return cmd + (["--conversation", session_id] if resume else [])
    if slot.vendor == "claude":
        cmd = ["claude", "-p", "--output-format", "stream-json", "--verbose",
               "--plugin-dir", str(bundle_dir(slot)),
               "--settings", claude_settings_arg(slot, role_class)]
        if mode:
            cmd += ["--permission-mode", mode]
    else:
        cmd = ["gemini", "-p", "Follow the Hive wake notice provided on standard input.",
               "-o", "stream-json", "-e", "hive", *gemini_policy_args(slot, role_class)]
        if mode:
            cmd += ["--approval-mode", mode]
    return cmd + model_flags(slot) + session_flags(slot.vendor, session_id, resume)


def build_interactive_command(slot: Slot, session_id: str, resume: bool,
                              initial_prompt: str | None,
                              role_class: str = "worker") -> list[str]:
    """Native interactive CLI with Hive capabilities attached for this session only."""
    if slot.vendor == "codex":
        cmd = ["codex", *(["resume"] if resume else []), *CODEX_SESSION_FLAGS,
               *codex_mode_flags(slot.permission_mode, headless=False), *model_flags(slot)]
        return cmd + ([session_id] if resume else []) + (
            [initial_prompt] if initial_prompt else [])
    if slot.vendor == "agy":
        cmd = ["agy", *(["--conversation", session_id] if resume else []),
               *(["--mode", slot.permission_mode] if slot.permission_mode else []),
               *model_flags(slot)]
        return cmd + (["-i", initial_prompt] if initial_prompt else [])
    if slot.vendor == "claude":
        cmd = ["claude", "--plugin-dir", str(bundle_dir(slot)),
               "--settings", claude_settings_arg(slot, role_class)]
        if slot.permission_mode:
            cmd += ["--permission-mode", slot.permission_mode]
        cmd += model_flags(slot) + session_flags("claude", session_id, resume)
        return cmd + ([initial_prompt] if initial_prompt else [])
    cmd = ["gemini", "-e", "hive", *gemini_policy_args(slot, role_class)]
    if slot.permission_mode:
        cmd += ["--approval-mode", slot.permission_mode]
    cmd += model_flags(slot) + session_flags("gemini", session_id, resume)
    return cmd + (["-i", initial_prompt] if initial_prompt else [])


def resolve(cmd: list[str]) -> list[str]:
    return [shutil.which(cmd[0]) or cmd[0], *cmd[1:]]


# ---------------------------------------------------------------------- stream formatting

def _short(v, n: int = 160) -> str:
    s = v if isinstance(v, str) else json.dumps(v, ensure_ascii=False, default=str)
    s = " ".join(s.split())
    return s if len(s) <= n else s[:n - 1] + "…"


def _tool_text(content) -> str:
    if isinstance(content, list):
        return " ".join(c.get("text", "") for c in content if isinstance(c, dict))
    return content if isinstance(content, str) else json.dumps(content, default=str)


def _codex_item(item: dict, done: bool) -> list[str]:
    """Lines for one Codex `item.started` / `item.completed` event."""
    kind, status = item.get("type"), item.get("status")
    if kind == "agent_message" and done:
        return [f"  {line}" for line in str(item.get("text", "")).strip().splitlines()]
    if kind == "command_execution":
        if not done:
            return [f"→ shell {_short(item.get('command', ''))}"]
        code, output = item.get("exit_code"), item.get("aggregated_output") or ""
        if code not in (0, None) or status == "failed":
            return [f"× exit {code}: {_short(output, 200)}"]
        return [f"← {_short(output, 200)}"]
    if kind == "file_change":
        if not done:
            return ["→ apply_patch " + _short(", ".join(
                f"{c.get('kind')} {c.get('path')}" for c in item.get("changes") or []))]
        return ["× patch failed"] if status == "failed" else []
    if kind == "mcp_tool_call":
        name = f"mcp__{item.get('server')}__{item.get('tool')}"
        if not done:
            return [f"→ {name} {_short(item.get('arguments') or {})}"]
        if item.get("error") or status == "failed":
            err = item.get("error")
            return [f"× {_short(err.get('message', err) if isinstance(err, dict) else err, 200)}"]
        result = item.get("result") or {}
        return [f"← {_short(_tool_text(result.get('content', result)), 200)}"]
    if kind == "web_search" and done:
        return [f"→ web_search {_short(item.get('query', ''))}"]
    if kind == "error" and done and CODEX_HOOK_TRUST_NOTICE not in str(item.get("message")):
        return [f"· {_short(item.get('message', ''), 300)}"]  # warnings; fatal ones: turn.failed
    return []


def _agy_event(ev: dict) -> list[str]:
    """Lines for one agy stream-json event: `init`, `step_update` or `result`."""
    kind = ev.get("event")
    if kind == "init":
        model = (ev.get("init") or {}).get("model")
        return [f"· session {ev.get('conversation_id', '')} started"
                + (f" ({model})" if model else "")]
    if kind == "result":
        r = ev.get("result") or {}
        out = []
        for d in r.get("denied_actions") or []:  # headless agy refuses, then ends the turn
            out.append(f"× needed a permission nobody could give: "
                       f"{d.get('action')} ({d.get('display_name')})")
        if r.get("status") == "SUCCESS":
            return out + ["· turn done"]
        return out + [f"· turn error: {_short(r.get('error') or r.get('status'), 300)}"]
    s = ev.get("step_update") or {}
    if s.get("step_type") == "agent_response":
        text = s.get("text_delta") or ""
        return [f"  {line}" for line in text.splitlines() if line.strip()]
    if s.get("step_type") != "tool":
        return []
    info = s.get("tool_info") or {}
    if s.get("state") == "ACTIVE":
        params = info.get("parameters") or {}
        if info.get("name") == "call_mcp_tool":
            return [f"→ mcp__{params.get('ServerName')}__{params.get('ToolName')} "
                    f"{_short(params.get('Arguments') or {})}"]
        return [f"→ {info.get('name') or s.get('tool_name')} {_short(params)}"]
    if s.get("state") == "ERROR":
        err = info.get("error") or {}
        return [f"× {_short(err.get('message', err) if isinstance(err, dict) else err, 300)}"]
    return [f"← {_short(info['output'], 200)}"] if info.get("output") else []


def format_stream_event(ev: dict) -> list[str]:
    """Human-readable lines for one stream-json event (Claude Code, Gemini CLI, Codex or
    agy)."""
    if "event" in ev:
        return _agy_event(ev)
    t = ev.get("type")
    out: list[str] = []
    # Codex
    if t in ("item.started", "item.completed") and isinstance(ev.get("item"), dict):
        return _codex_item(ev["item"], done=t == "item.completed")
    if t == "thread.started":
        return [f"· session {ev.get('thread_id', '')} started"]
    if t == "turn.completed":
        return ["· turn done"]
    if t == "turn.failed":
        err = ev.get("error") or {}
        return [f"· turn error: {_short(err.get('message', err), 300)}"]
    # Claude Code
    if t == "assistant" and isinstance(ev.get("message"), dict):
        for c in ev["message"].get("content", []):
            if c.get("type") == "text" and c.get("text", "").strip():
                out += [f"  {line}" for line in c["text"].strip().splitlines()]
            elif c.get("type") == "tool_use":
                out.append(f"→ {c.get('name')} {_short(c.get('input', {}))}")
        return out
    if t == "user" and isinstance(ev.get("message"), dict):
        for c in ev["message"].get("content", []):
            if isinstance(c, dict) and c.get("type") == "tool_result":
                mark = "×" if c.get("is_error") else "←"
                out.append(f"{mark} {_short(_tool_text(c.get('content')), 200)}")
        return out
    if t == "system" and ev.get("subtype") == "init":
        return [f"· session {ev.get('session_id', '')} started ({ev.get('model', '')})"]
    # Gemini CLI
    if t == "init":
        return [f"· session {ev.get('session_id', '')} started ({ev.get('model', '')})"]
    if t == "message" and ev.get("role") == "assistant":
        text = ev.get("content", "")
        return [f"  {line}" for line in str(text).splitlines() if line.strip()]
    if t == "tool_use":
        return [f"→ {ev.get('tool_name')} {_short(ev.get('parameters', {}))}"]
    if t == "tool_result":
        mark = "×" if ev.get("status") == "error" else "←"
        return [f"{mark} {_short(ev.get('output') or ev.get('error') or '', 200)}"]
    if t == "error":
        return [f"× error: {_short(ev.get('message', ev), 300)}"]
    # Both
    if t == "result":
        status = "error" if ev.get("is_error") or ev.get("status") == "error" else "done"
        cost = ev.get("total_cost_usd")
        return [f"· turn {status}" + (f" ({ev.get('num_turns')} turns)" if ev.get("num_turns")
                                        else "") + (f" ${cost:.2f}" if cost else "")]
    return out


class DeltaJoiner:
    """Gemini CLI and agy stream assistant text as deltas; join them into whole lines."""

    def __init__(self):
        self.buf = ""

    def feed(self, ev: dict) -> list[str]:
        if ev.get("type") == "message" and ev.get("role") == "assistant" and ev.get("delta"):
            return self._add(str(ev.get("content", "")))
        s = ev.get("step_update") if ev.get("event") == "step_update" else None
        if isinstance(s, dict) and s.get("step_type") == "agent_response" \
                and s.get("text_delta") is not None:
            lines = self._add(str(s["text_delta"]))
            return lines + (self.flush() if s.get("state") != "ACTIVE" else [])
        lines = self.flush()
        return lines + format_stream_event(ev)

    def _add(self, text: str) -> list[str]:
        self.buf += text
        *done, self.buf = self.buf.split("\n")
        return [f"  {l}" for l in done if l.strip()]

    def flush(self) -> list[str]:
        out = [f"  {self.buf}"] if self.buf.strip() else []
        self.buf = ""
        return out


