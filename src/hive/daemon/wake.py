"""Launching agent CLIs (SPEC §10).

Capabilities are attached per session only: Claude Code gets the repo's `.hive/agent/claude`
plugin via `--plugin-dir`; Gemini CLI gets the `.hive/agent/gemini` extension linked into the
slot's own GEMINI_CLI_HOME and selected with `-e hive`; Codex gets the `.hive/agent/codex`
profile, rules and skills copied into the slot's own CODEX_HOME and selected with `-p hive`.
Nothing is written to the CLIs' global or project settings, so sessions not started by Hive
never see Hive.

Workers run headless with stream-json (Codex: JSONL) output, which is formatted, shown and
uploaded live. The orchestrator runs as the native interactive CLI.
"""

