@dataclass
class WakeResult:
    returncode: int
    output: str
    quota_hit: bool
    duration: float
    session_id: str = ""  # reported by the CLI (Codex picks its own)
    usage: dict = field(default_factory=dict)  # see TokenMeter.summary()
    login_needed: bool = False  # the CLI's account isn't logged in


class TokenMeter:
    """Token usage of one headless turn, from the CLI's own stream events.

    - Claude Code: every `assistant` event carries its request's usage (repeated for each
      content block of the same message, so counted once per message id). The context size
      is the last request's input, cached or not.
    - Codex: `turn.completed` carries the turn's totals.
    - Gemini CLI: the final `result` event carries `stats`.
    - agy: each finished `agent_response` step carries its request's usage; input excludes
      the cached part, so the context is both together.
    """

    def __init__(self):
        self.input = self.output = self.requests = 0
        self.context = 0
        self._seen: set[str] = set()

    def feed(self, ev: dict) -> None:
        t = ev.get("type")
        if t == "assistant" and isinstance(ev.get("message"), dict):
            msg = ev["message"]
            u = msg.get("usage") or {}
            mid = msg.get("id") or ""
            if not u or (mid and mid in self._seen):
                return
            self._seen.add(mid)
            ctx = (int(u.get("input_tokens") or 0) + int(u.get("cache_read_input_tokens") or 0)
                   + int(u.get("cache_creation_input_tokens") or 0))
            self.input += ctx
            self.output += int(u.get("output_tokens") or 0)
            self.requests += 1
            self.context = ctx
        elif t == "turn.completed" and isinstance(ev.get("usage"), dict):  # Codex
            u = ev["usage"]
            self.input += int(u.get("input_tokens") or 0)
            self.output += int(u.get("output_tokens") or 0)
        elif t == "result" and isinstance(ev.get("stats"), dict) and not self.requests:  # Gemini
            s = ev["stats"]
            self.input += int(s.get("input_tokens") or 0)
            self.output += int(s.get("output_tokens") or 0)
        elif ev.get("event") == "step_update":  # agy
            s = ev.get("step_update") or {}
            u = s.get("usage")
            if s.get("step_type") != "agent_response" or s.get("state") == "ACTIVE" \
                    or not isinstance(u, dict):
                return
            key = f"{s.get('conversation_id')}:{s.get('step_index')}"
            if key in self._seen:
                return
            self._seen.add(key)
            ctx = int(u.get("input_tokens") or 0) + int(u.get("cache_read_tokens") or 0)
            self.input += ctx
            self.output += int(u.get("output_tokens") or 0) + int(u.get("thinking_tokens") or 0)
            self.requests += 1
            self.context = ctx

    def summary(self) -> dict:
        return {"input": self.input, "output": self.output, "requests": self.requests,
                "context": self.context}

    def line(self) -> str | None:
        if not (self.input or self.output):
            return None
        ctx = f", context {self.context / 1000:.0f}k" if self.context else ""
        return (f"· tokens: {self.input / 1000:.0f}k in, {self.output / 1000:.1f}k out"
                + (f" over {self.requests} requests" if self.requests else "") + ctx)


def run_cli(slot: Slot, cmd: list[str], prompt: str, env: dict, log_path: Path,
            timeout: float = 3600, on_start=None,
            on_lines: Callable[[list[str]], None] | None = None) -> WakeResult:
    t0 = time.time()
    proc = subprocess.Popen(resolve(cmd), cwd=slot.worktree, env=env, stdin=subprocess.PIPE,
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                            encoding="utf-8", errors="replace", bufsize=1,
                            **popen_group_kwargs())
    if on_start:
        on_start(proc)
    killer = threading.Timer(timeout, kill_tree, args=(proc,))  # the CLI and its children
    killer.daemon = True
    killer.start()
    try:
        proc.stdin.write(agy_message(prompt) if slot.vendor == "agy" else prompt)
        proc.stdin.close()
    except OSError:
        pass
    raw: deque[str] = deque(maxlen=400)  # only the tail is needed (quota detection, log)
    is_error = False
    session_id = ""
    meter = TokenMeter()
    joiner = DeltaJoiner()
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with open(log_path, "a", encoding="utf-8") as log:
        log.write(f"\n===== wake {time.strftime('%Y-%m-%d %H:%M:%S')} =====\n")
        for line in proc.stdout:
            raw.append(line)
            log.write(line)
            try:
                ev = json.loads(line)
            except ValueError:
                m = _CODEX_LOG.match(line)  # e.g. a tool call refused by Hive's hook
                lines = [f"× {m.group(1)}"] if m else [line.rstrip()] if line.strip() else []
            else:
                if isinstance(ev, dict):
                    meter.feed(ev)
                    if ev.get("type") == "result":
                        is_error = bool(ev.get("is_error")) or ev.get("status") == "error"
                    elif ev.get("type") == "turn.failed":  # Codex
                        is_error = True
                    elif ev.get("type") == "thread.started":  # Codex
                        session_id = str(ev.get("thread_id") or "")
                    elif ev.get("event") == "init":  # agy
                        session_id = str(ev.get("conversation_id") or "")
                    elif ev.get("event") == "result":  # agy
                        is_error = (ev.get("result") or {}).get("status") != "SUCCESS"
                    lines = joiner.feed(ev)
                else:
                    lines = []
            if lines and on_lines:
                on_lines(lines)
        tail = joiner.flush()
        if meter.line():
            tail.append(meter.line())
            log.write(meter.line() + "\n")
        if tail and on_lines:
            on_lines(tail)
    proc.wait()
    killer.cancel()
    out = "".join(raw)
    is_error = is_error or proc.returncode != 0
    login = is_error and bool(LOGIN_RE.search(out[-5000:]))
    quota = is_error and not login and bool(QUOTA_RE.search(out[-5000:]))
    return WakeResult(proc.returncode or 0, out, quota, time.time() - t0, session_id,
                      meter.summary(), login)
